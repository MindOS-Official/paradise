#!/usr/bin/env bash
# MindOS Paradise kernel config optimizasyonu (Debian 6.12 config tabanı -> 7.2.x)
set -e
cd "${1:?kernel kaynak dizini}"
C=scripts/config

# Kimlik: uname -r -> 7.2.10-mindos
$C --set-str LOCALVERSION "-mindos" -d LOCALVERSION_AUTO

# Debian'a özel imza anahtarları / modül imzası kapat (derleme hatası + boyut)
$C --set-str SYSTEM_TRUSTED_KEYS "" --set-str SYSTEM_REVOCATION_KEYS "" -d MODULE_SIG -d MODULE_SIG_ALL

# Debug sembolleri kapalı -> çok daha küçük modüller, hızlı derleme
$C -d DEBUG_INFO -d DEBUG_INFO_DWARF5 -d DEBUG_INFO_DWARF_TOOLCHAIN_DEFAULT -d DEBUG_INFO_BTF -e DEBUG_INFO_NONE

# Masaüstü tepkiselliği: tam preempt + 1000Hz
$C -d PREEMPT_VOLUNTARY -e PREEMPT -e PREEMPT_DYNAMIC
$C -d HZ_250 -e HZ_1000 --set-val HZ 1000

# Sıkıştırma: zstd (hızlı açılış, küçük boyut)
$C -d KERNEL_GZIP -d KERNEL_XZ -e KERNEL_ZSTD
$C -d MODULE_COMPRESS_XZ -e MODULE_COMPRESS_ZSTD -e MODULE_COMPRESS_ALL -e MODULE_DECOMPRESS

# RAM: zswap varsayılan açık (zstd), zram zstd, MGLRU, THP sadece madvise
$C -e ZSWAP -e ZSWAP_DEFAULT_ON -e ZSWAP_SHRINKER_DEFAULT_ON \
   -d ZSWAP_COMPRESSOR_DEFAULT_LZO -e ZSWAP_COMPRESSOR_DEFAULT_ZSTD --set-str ZSWAP_COMPRESSOR_DEFAULT zstd
$C -m ZRAM -d ZRAM_DEF_COMP_LZ4 -e ZRAM_DEF_COMP_ZSTD --set-str ZRAM_DEF_COMP zstd
$C -e LRU_GEN -e LRU_GEN_ENABLED
$C -d TRANSPARENT_HUGEPAGE_ALWAYS -e TRANSPARENT_HUGEPAGE_MADVISE
$C -e KSM
# Statik per-cpu bellek yükünü azalt (Debian: 8192)
$C -d MAXSMP --set-val NR_CPUS 512

TARGET_ARCH=${2:-${ARCH:-$(uname -m)}}

# Masaüstünde gereksiz sunucu/egzotik donanım alt sistemleri (boyut)
for o in STAGING INFINIBAND HAMRADIO ATM ISDN CAN ARCNET FDDI WAN IEEE802154 6LOWPAN \
         RAPIDIO GREYBUS MEDIA_DIGITAL_TV_SUPPORT MEDIA_ANALOG_TV_SUPPORT MEDIA_SDR_SUPPORT \
         MLX4_CORE MLX5_CORE NET_VENDOR_CHELSIO NET_VENDOR_HUAWEI NET_VENDOR_CAVIUM \
         SCSI_DEBUG KUNIT RUNTIME_TESTING_MENU; do
  $C -d $o
done

if [ "$TARGET_ARCH" = "aarch64" ] || [ "$TARGET_ARCH" = "arm64" ]; then
  # ARM64 masaüstü ve çoklu donanım (Apple Silicon, Raspberry Pi 4/5, Snapdragon X Elite, Ampere Altra)
  $C -e ARM64 -e ARM64_4K_PAGES -d ARM64_64K_PAGES -e ARM64_VA_BITS_48 -e COMPAT
  $C -e EFI_STUB -e EFI -e ACPI -e ACPI_APEI -e ACPI_CPPC_CPUFREQ
  $C -e SERIAL_AMBA_PL011 -e SERIAL_AMBA_PL011_CONSOLE
  $C -e PCI_HOST_GENERIC -e DRM_SIMPLEDRM

  # Device Tree (OF) desteği
  $C -e OF -e OF_FLATTREE -e OF_EARLY_FLATTREE -e OF_DYNAMIC -e OF_ADDRESS -e OF_IRQ \
     -e OF_NET -e OF_RESERVED_MEM -e OF_RESOLVE -e OF_OVERLAY -e OF_CONFIGFS

  # Apple Silicon (M1/M2 Mac mini, MacBook Air/Pro - Asahi Linux)
  $C -e ARCH_APPLE -e ARM_APPLE_SOC_CPUFREQ -e APPLE_AIC -e APPLE_WATCHDOG -e PINCTRL_APPLE_SPMI \
     -e APPLE_SART -e APPLE_DART -e APPLE_MAILBOX -e APPLE_RTKIT -m APPLE_RTKIT_HELPER \
     -e NVME_APPLE -e PCIE_APPLE_MSI_DOORBELL -e SPI_APPLE -e I2C_APPLE -e COMMON_CLK_APPLE_NCO \
     -m DRM_APPLETBDRM -m SND_SOC_APPLE_MCA -m SND_SOC_CS42L83 -m SND_SOC_CS42L84 \
     -m KEYBOARD_APPLESPI -m HID_APPLE -m HID_APPLEIR -m HID_MAGICMOUSE \
     -m BT_HCIBCM4377 -m BRCMFMAC -e BRCMFMAC_PCIE -e BRCMFMAC_SDIO \
     -e POWER_RESET_APPLE_POWEROFF -e APPLE_PMGR_PWRSTATE -e ARM_APPLE_SOC_PCPU_PMU

  # Raspberry Pi 4 & Raspberry Pi 5 (RPi foundation DTBs & bcm2711/bcm2712 modules)
  $C -e ARCH_BCM -e ARCH_BCM2835 -e SOC_BRCMSTB -e BCM2835_MBOX -e RASPBERRYPI_FIRMWARE \
     -e RASPBERRYPI_POWER -e BCM2835_WDT -e BCM2835_POWER -m BCM2711_THERMAL \
     -m ARM_RASPBERRYPI_CPUFREQ -m BCM_GENET -e PCIE_BRCMSTB -e MMC_BCM2835 \
     -e MMC_SDHCI_IPROC -e MMC_SDHCI_BRCMSTB -e PINCTRL_BCM2835 \
     -m RP1 -m MISC_RP1 -m RP1_PIO -m PINCTRL_RP1 -m DRM_VC4 -m DRM_V3D \
     -m DRM_RP1_VEC -m DRM_RP1_DSI -m SND_BCM2835 -m SND_BCM2835_SOC_I2S -m PWM_BCM2835

  # Snapdragon X Elite (X1E80100) & UEFI ARM64 dizüstü bilgisayarlar
  $C -e ARCH_QCOM -e QCOM_SCM -e QCOM_RPMH -e QCOM_RPMHPD -e QCOM_COMMAND_DB \
     -e ARM_QCOM_CPUFREQ_HW -e PINCTRL_MSM -e PINCTRL_SC8280XP -e PINCTRL_X1E80100 \
     -e INTERCONNECT_QCOM -e INTERCONNECT_QCOM_RPMH -e INTERCONNECT_QCOM_X1E80100 \
     -e REGULATOR_QCOM_RPMH -e POWER_RESET_QCOM_PON -e PCIE_QCOM \
     -m DRM_MSM -e DRM_MSM_DP -e DRM_MSM_DSI -m ATH11K -m ATH11K_PCI -m ATH12K

  # Ampere Altra & Enterprise ARM64
  $C -e ARM_AMPERE_CPUFREQ -e EDAC -m EDAC_ALTRA -m EDAC_ALTRA_EI -m ARM_SBSA_WATCHDOG
else
  $C -d X86_NATIVE_CPU
fi
